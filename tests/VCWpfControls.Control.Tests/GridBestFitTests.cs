using VCWpfControls.Control.Tests.Infrastructure;
using VCWpfControls.Grid;
using VCWpfControls.Grid.Columns;
using Xunit;
using static VCWpfControls.Control.Tests.TestModels;

namespace VCWpfControls.Control.Tests;

public class GridBestFitTests
{
    [StaFact]
    public void AutoGeneratedColumns_DefaultToAutoWidth()
    {
        var grid = new GridControl();
        var window = TestWindowHost.Show(grid);
        grid.ItemsSource = CreateEmployees(5);
        TestWindowHost.Pump();

        try
        {
            Assert.NotEmpty(grid.Columns);
            Assert.All(grid.Columns, column => Assert.True(column.Width.IsAuto, $"column {column.FieldName} should default to Auto"));
            // Auto widths start from the header content once laid out.
            Assert.All(grid.Layout.Slots, slot => Assert.True(slot.Width > 0));
        }
        finally
        {
            window.Close();
        }
    }

    [StaFact]
    public void AutoColumns_ExceedingViewport_ShowHorizontalScrollbar()
    {
        var grid = new GridControl { Width = 220 };
        var window = TestWindowHost.Show(grid);
        var data = CreateEmployees(4);
        foreach (var employee in data)
        {
            employee.Name = "Very Long Employee Name " + employee.Id;
            employee.Department = "Extremely Long Department " + employee.Id;
        }

        grid.ItemsSource = data;
        TestWindowHost.Pump();

        try
        {
            // All-auto content wider than the 220px viewport -> extent exceeds viewport.
            Assert.True(grid.Layout.TotalWidth > grid.ViewportWidth,
                $"total {grid.Layout.TotalWidth:F0} should exceed viewport {grid.ViewportWidth:F0}");
            var scrollbar = grid.Template.FindName("PART_HorizontalScrollBar", grid) as System.Windows.Controls.Primitives.ScrollBar;
            Assert.NotNull(scrollbar);
            Assert.Equal(System.Windows.Visibility.Visible, scrollbar!.Visibility);
        }
        finally
        {
            window.Close();
        }
    }

    [StaFact]
    public void BestFitColumn_SizesToContent()
    {
        var grid = new GridControl();
        var window = TestWindowHost.Show(grid);
        var data = CreateEmployees(10);
        foreach (var employee in data)
        {
            employee.Name = "Short"; // uniform short content
            employee.Department = "SomeMediumDepartment";
        }

        grid.ItemsSource = data;
        TestWindowHost.Pump();

        try
        {
            var nameColumn = grid.Columns.First(c => c.FieldName == "Name");
            var emailColumn = grid.Columns.First(c => c.FieldName == "Department");

            grid.BestFitColumn(nameColumn);
            TestWindowHost.Pump();
            var nameWidth = nameColumn.Width;
            Assert.True(nameWidth.IsAbsolute);
            // Short uniform content: the column becomes narrow (header-driven, not star-wide).
            Assert.True(nameWidth.Value < 90, $"name width {nameWidth.Value:F0} should fit short content");

            grid.BestFitColumn(emailColumn);
            TestWindowHost.Pump();
            var emailWidth = emailColumn.Width;
            // Email content is wider than the header, so the column is wider than the name column.
            Assert.True(emailWidth.Value > nameWidth.Value,
                $"email {emailWidth.Value:F0} should be wider than name {nameWidth.Value:F0}");
        }
        finally
        {
            window.Close();
        }
    }

    [StaFact]
    public void BestFitAllColumns_RespectsRowSampling()
    {
        var grid = new GridControl();
        var window = TestWindowHost.Show(grid);
        grid.ItemsSource = CreateEmployees(30);
        TestWindowHost.Pump();

        try
        {
            grid.BestFitAllColumns(maxRowCount: 5);
            TestWindowHost.Pump();
            Assert.All(grid.Columns, column => Assert.True(column.Width.IsAbsolute));
        }
        finally
        {
            window.Close();
        }
    }

    [StaFact]
    public void BestFitColumn_RespectsMinWidth()
    {
        var grid = new GridControl();
        var window = TestWindowHost.Show(grid);
        grid.ItemsSource = CreateEmployees(3);
        TestWindowHost.Pump();

        try
        {
            var nameColumn = grid.Columns.First(c => c.FieldName == "Name");
            nameColumn.MinWidth = 200;
            grid.BestFitColumn(nameColumn);
            TestWindowHost.Pump();
            Assert.Equal(200d, nameColumn.Width.Value);
        }
        finally
        {
            window.Close();
        }
    }
}
